def draw(template):
    rows = [r for r in template.split("\n") if r.strip() != ""]
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    px = img.load()
    for y, row in enumerate(rows[:16]):
        row = (row + "." * 16)[:16]
        for x, ch in enumerate(row):
            colour = P.get(ch if ch != " " else '2')
            if colour:
                px[x, y] = colour
    return img


def armour_layer(index):
    """
    Слои брони 1.12.2 (64x32). Заготовка: пластины стального цвета с
    контуром по краям областей и редкими вис-вкраплениями. Слой 1 —
    шлем/торс/руки, слой 2 — поножи/ботинки.
    """
    img = Image.new("RGBA", (64, 32), (0, 0, 0, 0))
    px = img.load()
    boxes = [(0, 0, 64, 16), (16, 16, 40, 32)] if index == 1 \
        else [(0, 16, 16, 32), (16, 16, 40, 32)]
    for (x0, y0, x1, y1) in boxes:
        for y in range(y0, y1):
            for x in range(x0, x1):
                if x in (x0, x1 - 1) or y in (y0, y1 - 1):
                    px[x, y] = P['k']
                elif (x + y) % 9 == 0:
                    px[x, y] = P['3']
                elif (x * 3 + y) % 11 == 0:
                    px[x, y] = P['1']
                else:
                    px[x, y] = P['2']
    for (x, y) in [(7, 4), (23, 9), (41, 6), (12, 22), (30, 25), (36, 19)]:
        if px[x, y][3]:
            px[x, y] = P['P']
    return img


