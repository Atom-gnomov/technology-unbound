package unboundtech.common.tiles;

import net.minecraft.nbt.NBTTagCompound;

/**
 * Контракт машины, умеющей рассказать о себе.
 *
 * Канон `04_systems/machine_feedback.md` §4 требует, чтобы игрок мог узнать
 * причину простоя **без GUI** — по ПКМ пустой рукой. Полноценного интерфейса
 * у наших машин нет и не будет до T4, поэтому строка статуса — единственный
 * способ отличить «интерференция» от «нет узла» и от «буфер полон».
 *
 * §5 того же файла требует разборки ключом с сохранением содержимого —
 * отсюда пара методов для NBT дропа.
 */
public interface IMachineStatus {

    /**
     * @return строка статуса для ПКМ пустой рукой; уже локализованная
     */
    String getStatusLine();

    /** Пишет то, что обязано пережить разборку ключом (буфер EU и флаги). */
    void writeWrenchNBT(NBTTagCompound tag);

    /** Читает сохранённое при установке блока из «ключевого» дропа. */
    void readWrenchNBT(NBTTagCompound tag);
}
