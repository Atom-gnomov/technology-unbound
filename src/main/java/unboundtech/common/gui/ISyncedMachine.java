package unboundtech.common.gui;

/**
 * Машина с GUI (каркас ХФ-7): контейнер — только ТРАНСПОРТ int-полей,
 * источник правды для отрисовки — клиентская копия тайла.
 *
 * Сервер каждый тик отдаёт {@link #syncFields()}; контейнер шлёт клиенту
 * только изменившиеся индексы (sendWindowProperty), клиентский тайл
 * принимает их в {@link #applySyncField} и хранит у себя — GUI читает
 * значения из тайла, а не из контейнера.
 */
public interface ISyncedMachine {

    /** Снимок синхронизируемых полей; порядок индексов — контракт тайла. */
    int[] syncFields();

    /** Клиент: принять значение поля с сервера. */
    void applySyncField(int index, int value);
}
