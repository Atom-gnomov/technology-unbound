package unboundtech.energy;

/**
 * Параметры Таум-Оверклокера.
 *
 * Источник истины — карточка {@code docs/design/05_objects/thaumic_overclocker.md}
 * в репо порта; здесь только значения, которые может менять сборка.
 *
 * <p><b>Что изменилось против ранних набросков.</b> Оверклокер — не блок
 * рядом с машиной, а <b>предмет-апгрейд</b>: ускорение в IC2 применяется
 * только предметами в слотах апгрейдов ({@code InvSlotUpgrade} проверяет
 * {@code instanceof IProcessingUpgrade} и опрашивает множители). Отсюда два
 * следствия, из-за которых старые лимиты («очки нагрузки на чанк»,
 * «оверклокеров на механизм») удалены:
 * <ul>
 *   <li>число апгрейдов на машину задаёт сама IC2 — у стандартной машины
 *       {@code new InvSlotUpgrade(this, "upgrade", 4)}, повлиять на это мы
 *       не можем;</li>
 *   <li>учёт «по чанку» не нужен: носитель перегрузки — сам апгрейд, он
 *       греется в {@code onTick(stack, parent)} и при перегреве уходит в
 *       инертное состояние, выбрасывая флюкс над машиной.</li>
 * </ul>
 *
 * <p><b>Важно для реализации:</b> предмет обязан быть {@code maxStackSize = 1} —
 * IC2 возводит множитель в степень размера стопки ({@code Math.pow(mult,
 * stackCount)}), и стопка в одном слоте сломала бы баланс.
 */
public final class OverclockRules {

    /**
     * Множитель времени обработки за один апгрейд (родной оверклокер IC2 —
     * 0.7). Наш быстрее и при этом дешевле по энергии на операцию.
     */
    public static double PROCESS_TIME_MULTIPLIER = 0.6D;

    /**
     * Множитель потребления за один апгрейд (родной оверклокер IC2 — 1.6).
     * Итог: 0.6 × 1.2 = 0.72 EU на операцию против 1.12 у родного.
     */
    public static double ENERGY_DEMAND_MULTIPLIER = 1.2D;

    /** Ёмкость каждого из двух пулов заряда (Machina и Motus), единиц. */
    public static int CHARGE_CAPACITY = 32;

    /** Тиков активной работы машины на 1 единицу каждого аспекта. */
    public static int TICKS_PER_ESSENTIA_UNIT = 600;

    /** Нагрев за тик, пока машина обрабатывает. */
    public static int HEAT_PER_ACTIVE_TICK = 1;

    /** Остывание за тик, пока машина простаивает. */
    public static int COOLING_PER_IDLE_TICK = 2;

    /** Порог перегрева: на нём апгрейд глохнет и выбрасывает флюкс. */
    public static int HEAT_THRESHOLD = 6_000;

    /** Длительность инертного состояния после перегрева, тиков. */
    public static int INERT_TICKS = 600;

    /** Блоков флюкс-газа за одно событие перегрева. */
    public static int FLUX_PER_OVERHEAT = 1;

    private OverclockRules() {
    }

    /**
     * Проверка на «бесплатную скорость»: наш апгрейд должен быть выгоднее
     * родного, но не превращать машину в вечный двигатель — расход EU на
     * операцию обязан остаться положительным и заметным.
     *
     * @return множитель расхода EU на одну операцию (время × потребление)
     */
    public static double energyPerOperationMultiplier() {
        return PROCESS_TIME_MULTIPLIER * ENERGY_DEMAND_MULTIPLIER;
    }
}
